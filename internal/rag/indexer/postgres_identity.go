// parentReferenceStatements 用 PG 14 也支持的两条外键保留父块删除语义。
// 单列外键只清空 parent_chunk_id，复合外键在提交时校验知识库范围，collection_id 不会被清空。
var parentReferenceStatements = []string{
	`ALTER TABLE chunks DROP CONSTRAINT IF EXISTS chunks_parent_fk,DROP CONSTRAINT IF EXISTS chunks_parent_id_fk`,
	`ALTER TABLE chunks
 ADD CONSTRAINT chunks_parent_fk FOREIGN KEY(collection_id,parent_chunk_id)
  REFERENCES chunks(collection_id,id) DEFERRABLE INITIALLY DEFERRED,
 ADD CONSTRAINT chunks_parent_id_fk FOREIGN KEY(parent_chunk_id)
  REFERENCES chunks(id) ON DELETE SET NULL`,
}

// idFirstSchemaSQL 只调整新表的列顺序，不重建已有表，也不改写历史迁移校验和。
// 建表时先在首列预留自增标识，BIGINT 迁移再将它命名为 id；临时列不会出现在已提交的表中。
func idFirstSchemaSQL(sql string) string {
	for _, table := range []string{"documents", "chunks", "rag_collection_profiles", "rag_document_heads"} {
		create := "CREATE TABLE IF NOT EXISTS " + table + " ("
		sql = strings.Replace(sql, create, create+"\n __rag_identity BIGINT GENERATED BY DEFAULT AS IDENTITY,", 1)
		add := "ALTER TABLE " + table + " ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY"
		// chunks 原本把三个 ADD COLUMN 放在同一条 ALTER 中，先分开标识列。
		sql = strings.Replace(sql, add+",", add+";\n ALTER TABLE "+table, 1)
		sql = strings.Replace(sql, add+";", fmt.Sprintf(`IF EXISTS(SELECT 1 FROM pg_attribute
 WHERE attrelid='%s'::regclass AND attname='__rag_identity' AND NOT attisdropped) THEN
 ALTER TABLE %s RENAME COLUMN __rag_identity TO id;
ELSE
 %s;
END IF;`, table, table, add), 1)
	}
	return sql
}

// identityMigrationSQL 允许已经升级的文档库补装 PG 检索层。
// 共享表不重复运行旧迁移；历史校验和仍按冻结模板计算，不能改写已应用的迁移。
func identityMigrationSQL(sql string) string {
	if !strings.Contains(sql, "retrieval_index") {
		return ""
	}
	if strings.Contains(sql, "CREATE UNIQUE INDEX IF NOT EXISTS retrieval_index_id_key") {
		return "" // 新建检索表已直接使用 id 主键，无需重复建立唯一索引。
	}
	if !strings.Contains(sql, "CREATE TABLE IF NOT EXISTS retrieval_index") {
		return sql
	}
	return strings.NewReplacer(
		"chunk_id       TEXT NOT NULL", "chunk_id       BIGINT NOT NULL",
		"document_id    TEXT NOT NULL", "document_id    BIGINT NOT NULL",
		"NOT NULL UNIQUE", "NOT NULL",
		"PRIMARY KEY (collection_id, chunk_id)", "PRIMARY KEY (id),\n    UNIQUE (collection_id, chunk_id)",
	).Replace(sql)
}
