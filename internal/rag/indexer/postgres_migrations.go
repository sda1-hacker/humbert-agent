const SchemaVersion = 4
const DocumentSchemaVersion = 3

type migration struct {
	version    int
	name       string
	statements []string
}

// initialSchema 拼接初始表结构与索引语句，用于第一版迁移。
func initialSchema() []string {
	var out []string
	for _, sql := range schemaStatements {
		// 数据库扩展由迁移入口显式安装。
		if strings.Contains(sql, "CREATE EXTENSION") {
			continue
		}
		out = append(out, sql)
		switch {
		case strings.Contains(sql, "CREATE TABLE IF NOT EXISTS documents"):
			out = append(out, `ALTER TABLE documents ADD COLUMN IF NOT EXISTS markdown TEXT`)
		case strings.Contains(sql, "CREATE TABLE IF NOT EXISTS chunks"):
			out = append(out, `ALTER TABLE chunks ADD COLUMN IF NOT EXISTS chunk_type TEXT NOT NULL DEFAULT 'text'`,
				`ALTER TABLE chunks ADD COLUMN IF NOT EXISTS context_header TEXT NOT NULL DEFAULT ''`,
				`ALTER TABLE chunks ADD COLUMN IF NOT EXISTS parent_chunk_id TEXT`)
		case strings.Contains(sql, "CREATE TABLE IF NOT EXISTS retrieval_index"):
			out = append(out, `ALTER TABLE retrieval_index ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY`,
				`CREATE UNIQUE INDEX IF NOT EXISTS retrieval_index_id_key ON retrieval_index(id)`)
		}
	}
	return out
}

// vectorSchema 仅为首次初始化替换向量列维度，原始迁移模板保持冻结。
// 该维度会进入数据库保存的迁移校验和；已有数据库禁止通过改配置自动改变向量空间。
func vectorSchema(dimensions int) []string {
	statements := initialSchema()
	for i, sql := range statements {
		statements[i] = strings.ReplaceAll(sql, "HALFVEC(1024)", fmt.Sprintf("HALFVEC(%d)", dimensions))
	}
	return statements
}

